/**
 * Turns admin-edited text into the document shape the legal page renders.
 *
 * @returns {{ intro: string[], sections: { title: string, paragraphs: string[] }[] }}
 */
export function parseLegalText(text) {
    const document = { intro: [], sections: [] };

    text.split('\n')
        .map((line) => line.trim())
        .filter(Boolean)
        .forEach((line) => {
            if (line.startsWith('## ')) {
                document.sections.push({ title: line.slice(3).trim(), paragraphs: [] });
            } else if (document.sections.length) {
                document.sections.at(-1).paragraphs.push(line);
            } else {
                document.intro.push(line);
            }
        });

    return document;
}

/** A built-in document as editable text (its Arabic source), to start an admin's version from. */
export function builtInLegalText(name) {
    const { intro, sections } = BUILT_IN_DOCUMENTS[name];

    return [intro, ...sections.map((section) => [`## ${section.title}`, ...section.paragraphs].join('\n\n'))].join('\n\n');
}
